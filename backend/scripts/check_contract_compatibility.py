"""Fail when the published contract loses something a consumer already relies on.

Usage, from ``backend/``::

    uv run python scripts/check_contract_compatibility.py                 # frozen vs generated
    uv run python scripts/check_contract_compatibility.py --base other.json

The frozen document lives in ``docs/api/openapi-v1.json``; the generated one is what the running
application produces. Adding an endpoint, a response status or an optional field is allowed.
Removing or narrowing anything a client may already depend on is not: that needs a new version
prefix (``/api/v2``), not a silent edit.

Exit codes: ``0`` compatible, ``1`` breaking change, ``2`` could not read a document.
"""

import argparse
import json
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
FROZEN_CONTRACT = REPO_ROOT / "docs" / "api" / "openapi-v1.json"
GENERATED_CONTRACT = Path(__file__).resolve().parents[1] / "openapi.json"

Document = dict[str, Any]

_HTTP_METHODS = frozenset({"get", "put", "post", "delete", "options", "head", "patch", "trace"})


def _load(path: Path) -> Document:
    """Read a JSON document from ``path``."""
    return json.loads(path.read_text(encoding="utf-8"))


def _operations(document: Document) -> dict[tuple[str, str], Document]:
    """Map ``(path, method)`` to the operation object, ignoring non-operation keys."""
    operations: dict[tuple[str, str], Document] = {}
    for path, item in (document.get("paths") or {}).items():
        if not isinstance(item, dict):
            continue
        for method, operation in item.items():
            if method.lower() in _HTTP_METHODS and isinstance(operation, dict):
                operations[(path, method.lower())] = operation
    return operations


def _schemas(document: Document) -> dict[str, Document]:
    """Return the named schemas of the document."""
    components = document.get("components") or {}
    schemas = components.get("schemas") or {}
    return {name: schema for name, schema in schemas.items() if isinstance(schema, dict)}


def _ref_name(schema: object) -> str | None:
    """Return the schema name a ``$ref`` points at, or ``None``."""
    if isinstance(schema, dict):
        reference = schema.get("$ref")
        if isinstance(reference, str) and reference.startswith("#/components/schemas/"):
            return reference.rsplit("/", 1)[-1]
    return None


def _properties(schema: Document) -> dict[str, Document]:
    """Return the declared properties of a schema, following a top-level ``$ref`` once."""
    properties = schema.get("properties")
    return (
        {name: value for name, value in properties.items() if isinstance(value, dict)}
        if (isinstance(properties, dict))
        else {}
    )


def _required(schema: Document) -> set[str]:
    """Return the names a schema marks as required."""
    required = schema.get("required")
    return (
        {name for name in required if isinstance(name, str)}
        if isinstance(required, list)
        else set()
    )


def _enum_values(schema: Document) -> set[str] | None:
    """Return the allowed values of an enum schema, or ``None`` when it is not an enum."""
    values = schema.get("enum")
    if isinstance(values, list):
        return {json.dumps(value, sort_keys=True) for value in values}
    return None


def _missing(names: set[str], template: str) -> list[str]:
    """Return one message per name, in a stable order."""
    return [template.format(name=name) for name in sorted(names)]


def compare(base: Document, current: Document) -> list[str]:
    """List every change in ``current`` that breaks a client written against ``base``.

    Args:
        base: The published (frozen) contract.
        current: The contract generated by the application.

    Returns:
        One human-readable line per breaking change; empty when the change is compatible.
    """
    problems: list[str] = []

    base_operations = _operations(base)
    current_operations = _operations(current)
    problems.extend(
        _missing(
            {
                f"{method.upper()} {path}"
                for path, method in set(base_operations) - set(current_operations)
            },
            "removed operation {name}",
        )
    )

    base_schemas = _schemas(base)
    current_schemas = _schemas(current)
    problems.extend(_missing(set(base_schemas) - set(current_schemas), "removed schema {name}"))

    for name in sorted(set(base_schemas) & set(current_schemas)):
        problems.extend(_compare_schema(name, base_schemas[name], current_schemas[name]))

    for (path, method), operation in sorted(base_operations.items()):
        if (path, method) not in current_operations:
            continue
        problems.extend(
            _compare_operation(path, method, operation, current_operations[(path, method)])
        )

    return problems


def _compare_operation(path: str, method: str, base: Document, current: Document) -> list[str]:
    """Compare one operation: its responses and its security."""
    problems: list[str] = []
    where = f"{method.upper()} {path}"

    base_responses = base.get("responses") or {}
    current_responses = current.get("responses") or {}
    problems.extend(
        f"{where}: removed response {status}"
        for status in sorted(set(base_responses) - set(current_responses))
    )

    if base.get("security") and not current.get("security"):
        problems.append(f"{where}: removed the security requirement")

    base_body = (base.get("requestBody") or {}).get("content") or {}
    current_body = (current.get("requestBody") or {}).get("content") or {}
    problems.extend(
        f"{where}: removed request body {media_type}"
        for media_type in sorted(set(base_body) - set(current_body))
    )

    return problems


def _compare_schema(name: str, base: Document, current: Document) -> list[str]:
    """Compare one schema: its kind, enum values, required names and properties."""
    problems: list[str] = []

    base_type = base.get("type")
    current_type = current.get("type")
    if base_type != current_type and not (base_type is None or current_type is None):
        problems.append(f"schema {name}: type changed from {base_type!r} to {current_type!r}")

    base_enum = _enum_values(base)
    if base_enum is not None:
        current_enum = _enum_values(current)
        if current_enum is None:
            problems.append(f"schema {name}: enum became a plain value")
        else:
            problems.extend(
                f"schema {name}: removed enum value {value}"
                for value in sorted(base_enum - current_enum)
            )

    problems.extend(
        f"schema {name}: field {field!r} became required"
        for field in sorted(_required(current) - _required(base))
    )

    base_properties = _properties(base)
    current_properties = _properties(current)
    problems.extend(
        f"schema {name}: removed field {field!r}"
        for field in sorted(set(base_properties) - set(current_properties))
    )

    for field in sorted(set(base_properties) & set(current_properties)):
        problems.extend(
            _compare_property(f"{name}.{field}", base_properties[field], current_properties[field])
        )

    return problems


def _compare_property(where: str, base: Document, current: Document) -> list[str]:
    """Compare one property: nullable, enum values and the schema it points at."""
    problems: list[str] = []

    base_nullable = _is_nullable(base)
    if base_nullable and not _is_nullable(current):
        problems.append(f"property {where}: no longer nullable")

    base_enum = _enum_values(base)
    if base_enum is not None:
        current_enum = _enum_values(current)
        if current_enum is None:
            problems.append(f"property {where}: enum became a plain value")
        else:
            problems.extend(
                f"property {where}: removed enum value {value}"
                for value in sorted(base_enum - current_enum)
            )

    base_ref = _ref_name(base)
    current_ref = _ref_name(current)
    if base_ref is not None and current_ref != base_ref:
        problems.append(f"property {where}: schema changed from {base_ref} to {current_ref}")

    return problems


def _is_nullable(schema: Document) -> bool:
    """Whether a property accepts ``null``."""
    if schema.get("nullable") is True:
        return True
    variants = schema.get("anyOf") or schema.get("oneOf") or []
    return any(isinstance(variant, dict) and variant.get("type") == "null" for variant in variants)


def main(argv: list[str] | None = None) -> int:
    """Compare the frozen contract with a generated one and report breaking changes."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument(
        "--base",
        type=Path,
        default=FROZEN_CONTRACT,
        help="published contract to compare against (default: docs/api/openapi-v1.json)",
    )
    parser.add_argument(
        "--current",
        type=Path,
        default=GENERATED_CONTRACT,
        help="generated contract (default: backend/openapi.json)",
    )
    args = parser.parse_args(argv)

    try:
        base = _load(args.base)
        current = _load(args.current)
    except (OSError, json.JSONDecodeError) as exc:
        sys.stderr.write(f"cannot read a contract: {exc}\n")
        return 2

    problems = compare(base, current)
    if problems:
        sys.stderr.write("Breaking changes against the published contract:\n")
        for problem in problems:
            sys.stderr.write(f"  - {problem}\n")
        sys.stderr.write(
            "A breaking change needs a new version prefix (/api/v2) and approval from the PO "
            "and from whoever consumes the contract.\n"
        )
        return 1

    sys.stdout.write("OK: the generated contract is compatible with the published one\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
